-- ============================================================================
-- 1. DDL - ESTRUTURA DO BANCO DE DADOS
-- ============================================================================

-- Autores podem estar associados a varios livros.
CREATE TABLE IF NOT EXISTS autores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL
        CHECK (BTRIM(nome) <> ''),
    nacionalidade VARCHAR(100) NOT NULL
        CHECK (BTRIM(nacionalidade) <> ''),
    data_nascimento DATE NOT NULL
);

-- Cada livro pertence a exatamente um autor.
CREATE TABLE IF NOT EXISTS livros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL
        CHECK (BTRIM(titulo) <> ''),
    autor_id BIGINT NOT NULL
        REFERENCES autores (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    ano_publicacao INTEGER NOT NULL
        CHECK (ano_publicacao > 0),
    quantidade_disponivel INTEGER NOT NULL DEFAULT 0
        CHECK (quantidade_disponivel >= 0)
);

-- O email identifica cada cliente e deve ser unico.
CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL
        CHECK (BTRIM(nome) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE
        CHECK (POSITION('@' IN email) > 1),
    telefone VARCHAR(30) NOT NULL,
    CONSTRAINT clientes_telefone_nao_vazio_check
        CHECK (BTRIM(telefone) <> '')
);

-- Migracao para bancos criados antes da inclusao do telefone.
-- CREATE TABLE IF NOT EXISTS nao altera tabelas que ja existem.
ALTER TABLE clientes
    ADD COLUMN IF NOT EXISTS telefone VARCHAR(30);

-- Telefones antigos ausentes ou vazios recebem um valor explicito antes
-- de a coluna ser marcada como obrigatoria.
UPDATE clientes
SET telefone = 'Nao informado'
WHERE telefone IS NULL
   OR BTRIM(telefone) = '';

ALTER TABLE clientes
    ALTER COLUMN telefone SET NOT NULL;

-- Garante a restricao tambem em bancos antigos que nao a possuam.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'clientes_telefone_nao_vazio_check'
          AND conrelid = 'clientes'::regclass
    ) THEN
        ALTER TABLE clientes
            ADD CONSTRAINT clientes_telefone_nao_vazio_check
            CHECK (BTRIM(telefone) <> '');
    END IF;
END;
$$;

-- Cada emprestimo referencia um livro e um cliente.
CREATE TABLE IF NOT EXISTS emprestimos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id BIGINT NOT NULL
        REFERENCES livros (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    cliente_id BIGINT NOT NULL
        REFERENCES clientes (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    data_emprestimo DATE NOT NULL,
    data_devolucao DATE,
    status VARCHAR(10) NOT NULL DEFAULT 'ativo'
        CHECK (status IN ('ativo', 'devolvido')),
    CONSTRAINT emprestimos_status_data_devolucao_check
        CHECK (
            (status = 'ativo' AND data_devolucao IS NULL)
            OR (status = 'devolvido' AND data_devolucao IS NOT NULL)
        ),
    CONSTRAINT emprestimos_datas_check
        CHECK (
            data_devolucao IS NULL
            OR data_devolucao >= data_emprestimo
        )
);


