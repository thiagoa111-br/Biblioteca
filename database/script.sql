-- ============================================================================
-- 3. RELATORIOS
-- ============================================================================

-- 3.1. Livros com exemplares disponiveis.
SELECT
    livros.id,
    livros.titulo,
    autores.nome AS autor,
    livros.quantidade_disponivel
FROM livros
INNER JOIN autores
    ON autores.id = livros.autor_id
WHERE livros.quantidade_disponivel > 0
ORDER BY livros.titulo;

-- 3.2. Livros que possuem emprestimos ativos.
SELECT
    livros.id,
    livros.titulo,
    COUNT(emprestimos.id) AS emprestimos_ativos
FROM livros
INNER JOIN emprestimos
    ON emprestimos.livro_id = livros.id
WHERE emprestimos.status = 'ativo'
GROUP BY livros.id, livros.titulo
ORDER BY emprestimos_ativos DESC, livros.titulo;

-- 3.3. Quantidade de livros por autor, inclusive autores sem livros.
SELECT
    autores.id,
    autores.nome,
    COUNT(livros.id) AS quantidade_livros
FROM autores
LEFT JOIN livros
    ON livros.autor_id = autores.id
GROUP BY autores.id, autores.nome
ORDER BY quantidade_livros DESC, autores.nome;

-- 3.4. Quantidade de emprestimos por livro, inclusive livros nunca emprestados.
SELECT
    livros.id,
    livros.titulo,
    COUNT(emprestimos.id) AS quantidade_emprestimos
FROM livros
LEFT JOIN emprestimos
    ON emprestimos.livro_id = livros.id
GROUP BY livros.id, livros.titulo
ORDER BY quantidade_emprestimos DESC, livros.titulo;

-- 3.5. Clientes que possuem emprestimos ativos.
SELECT
    clientes.id,
    clientes.nome,
    clientes.email,
    COUNT(emprestimos.id) AS emprestimos_ativos
FROM clientes
INNER JOIN emprestimos
    ON emprestimos.cliente_id = clientes.id
WHERE emprestimos.status = 'ativo'
GROUP BY clientes.id, clientes.nome, clientes.email
ORDER BY emprestimos_ativos DESC, clientes.nome;

-- 3.6. Historico detalhado dos emprestimos mais recentes.
SELECT
    emprestimos.id,
    livros.titulo AS livro,
    clientes.nome AS cliente,
    emprestimos.data_emprestimo,
    emprestimos.data_devolucao,
    emprestimos.status
FROM emprestimos
INNER JOIN livros
    ON livros.id = emprestimos.livro_id
INNER JOIN clientes
    ON clientes.id = emprestimos.cliente_id
ORDER BY emprestimos.data_emprestimo DESC, emprestimos.id DESC
LIMIT 20;
